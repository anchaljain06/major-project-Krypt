/**
 * Build evaluation/attack-matrix.md from the per-attack result JSON written by
 * run-v0.mjs / run-v1.mjs. This script is the only source of that file: edit
 * the template here, not the generated Markdown.
 *
 * Usage: node evaluation/attacks/build-matrix.mjs [resultsDir]
 *   resultsDir holds v0/ and v1/ subdirectories of <attack>.json (+ .png) files;
 *   default results/attack-matrix-dev.
 */
import { readFileSync, readdirSync, writeFileSync, existsSync } from "node:fs";
import { basename, dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";
import { ATTACKS } from "./attacks.mjs";

const HERE = dirname(fileURLToPath(import.meta.url));
const EVAL = join(HERE, "..");
const resultsDir = process.argv[2] ? join(process.cwd(), process.argv[2]) : join(EVAL, "results", "attack-matrix-dev");

function load(dir) {
  const out = {};
  if (!existsSync(dir)) return out;
  for (const f of readdirSync(dir).filter((f) => f.endsWith(".json"))) {
    try {
      out[basename(f, ".json")] = JSON.parse(readFileSync(join(dir, f), "utf8"));
    } catch {
      /* ignore unreadable files */
    }
  }
  return out;
}

const v0 = load(join(resultsDir, "v0"));
const v1 = load(join(resultsDir, "v1"));

const cell = (v) => (v === undefined || v === null || v === "" ? "—" : String(v).replace(/\|/g, "\\|").replace(/\n/g, " "));
const shot = (flavor, id) => {
  const p = join(resultsDir, flavor, `${id}.png`);
  return existsSync(p) ? `[${flavor}](${relative(EVAL, p)})` : "";
};

const rows = ATTACKS.map((a) => {
  const v0obs = a.kt ? "n/a (no KT in v0)" : v0[a.id]?.observed ?? "not run";
  const v1obs = v1[a.id]?.observed ?? "not run";
  const ev = [shot("v0", a.id), shot("v1", a.id)].filter(Boolean).join(" ");
  return `| \`${a.id}\` | ${cell(a.relay)} | ${cell(a.expected)} | ${cell(v0obs)} | ${cell(v1obs)} | ${cell(ev)} |`;
});

const v0Missing = ATTACKS.filter((a) => !a.kt && !v0[a.id]).map((a) => a.id);
const v1Missing = ATTACKS.filter((a) => !v1[a.id]).map((a) => a.id);
const status =
  v0Missing.length || v1Missing.length
    ? `**Status: partial.** ${[
        v1Missing.length ? `Not run on v1: ${v1Missing.join(", ")}.` : "Every v1 attack ran.",
        v0Missing.length ? `Not run on v0: ${v0Missing.join(", ")}.` : "",
      ]
        .filter(Boolean)
        .join(" ")}`
    : "**Status: complete.** Every attack ran on both versions.";
const runDate = basename(resultsDir).match(/\d{4}-\d{2}-\d{2}/)?.[0] ?? new Date().toISOString().slice(0, 10);

const md = `# Attack matrix: v0 vs v1 under a malicious relay

Generated by \`attacks/build-matrix.mjs\` from \`${relative(EVAL, resultsDir)}/\` (run ${runDate}); do not edit by hand.
Two real browser clients (Playwright, Chromium) talk through a relay in \`EVIL_MODE\` (\`primary-backend/src/evil.ts\`).
v0 is tag \`protocol-v0\`, which has no evil mode, so the same transforms are applied by a Socket.io proxy
(\`attacks/evil-proxy.mjs\`) that reuses the compiled \`evil.ts\`. \`impersonation\` and \`bola\` are checked in Node.

${status}

| Attack | What the relay does | Expected secure behaviour | v0 observed | v1 observed | Screenshot |
|---|---|---|---|---|---|
${rows.join("\n")}

How to rerun: [evaluation/README.md, "Attack matrix"](README.md#attack-matrix).
`;

writeFileSync(join(EVAL, "attack-matrix.md"), md);
console.log(`Wrote attack-matrix.md (v0: ${Object.keys(v0).length} results, v1: ${Object.keys(v1).length})`);
