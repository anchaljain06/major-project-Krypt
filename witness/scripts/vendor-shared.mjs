#!/usr/bin/env node
// Copies the built Krypt shared package (../shared/dist) into lib/krypt-shared/.
//
// The witness is meant to move to its own repository (krypt-witness), where
// ../shared will not exist, so it carries a vendored JS copy instead of a
// relative import. Re-run after changing shared/:
//
//   node scripts/vendor-shared.mjs            # builds ../shared, then copies
//   node scripts/vendor-shared.mjs --check    # exits 1 if the copy is stale

import { execFileSync } from "node:child_process";
import { mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const sharedDir = resolve(here, "../../shared");
const dest = resolve(here, "../lib/krypt-shared");
const check = process.argv.includes("--check");

execFileSync("npm", ["run", "--silent", "build"], { cwd: sharedDir, stdio: "inherit" });
const sharedCommit = (() => {
  try {
    return execFileSync("git", ["-C", sharedDir, "log", "-1", "--format=%h", "--", "."], { encoding: "utf8" }).trim();
  } catch {
    return "unknown";
  }
})();

const dist = join(sharedDir, "dist");
const files = readdirSync(dist).filter((f) => f.endsWith(".js")).sort();
const header = (f) =>
  `// GENERATED by witness/scripts/vendor-shared.mjs from shared/src/${f.replace(/\.js$/, ".ts")}. Do not edit.\n`;

const wanted = new Map(files.map((f) => [f, header(f) + readFileSync(join(dist, f), "utf8")]));
wanted.set("VERSION", `shared@${sharedCommit}\n`);

if (check) {
  const stale = [...wanted].filter(([f, body]) => {
    if (f === "VERSION") return false;
    try {
      return readFileSync(join(dest, f), "utf8") !== body;
    } catch {
      return true;
    }
  });
  if (stale.length) {
    console.error(`lib/krypt-shared is stale: ${stale.map(([f]) => f).join(", ")}`);
    process.exit(1);
  }
  console.log("lib/krypt-shared is up to date");
} else {
  rmSync(dest, { recursive: true, force: true });
  mkdirSync(dest, { recursive: true });
  for (const [f, body] of wanted) writeFileSync(join(dest, f), body);
  console.log(`vendored ${files.length} files from shared@${sharedCommit} into lib/krypt-shared`);
}
